class _TrimRow extends StatelessWidget {
  const _TrimRow({
    required this.id,
    required this.label,
    required this.trimmed,
    required this.baseLabel,
    required this.trimLabel,
    required this.enabled,
    required this.onChanged,
  });

  final String id;
  final String label;
  final bool trimmed;
  final String baseLabel;
  final String trimLabel;
  final bool enabled;
  final ValueChanged<bool> onChanged;

  @override
  Widget build(BuildContext context) {
    return Row(
      children: [
        SizedBox(
          width: 54,
          child: Text(
            label,
            style:
                const TextStyle(color: Colors.white54, fontSize: 12),
          ),
        ),
        Expanded(
          child: Text(
            trimmed ? trimLabel : baseLabel,
            style: TextStyle(
              color: trimmed
                  ? const Color(0xFF00D4AA)
                  : Colors.white38,
              fontSize: 12,
              fontWeight: FontWeight.w500,
            ),
          ),
        ),
        Transform.scale(
          scale: 0.85,
          child: Switch(
            key: ValueKey(id),
            value: trimmed,
            onChanged: enabled ? onChanged : null,
            activeThumbColor: const Color(0xFF00D4AA),
            inactiveThumbColor: Colors.white38,
            inactiveTrackColor: Colors.white12,
          ),
        ),
