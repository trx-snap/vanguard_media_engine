//
// Proves that VGEditorController and VGEditorDraft correctly coordinate the
// Phase 7.6-proven dev_ MethodChannel routes through the new formal API.
//
// This playground is additive and does NOT modify the existing raw
// vanguard_timeline_playback_playground.dart (Stage 7.6 regression baseline).
//
// PROOF CRITERIA:
//   1. initialize() produces a valid textureId and 10s draft duration.
//   2. play() / pause() toggle playback via VGEditorController state.
//   3. Seek slider updates currentPTS via handleNativeCallback delegation.
//   4. Trim A → 3s: updateDraft() rebuilds to ~8s timeline.
//   5. Trim B → 3s: updateDraft() rebuilds to ~6s timeline.
//   6. Reset: updateDraft() rebuilds back to 10s baseline.
//   7. Export after trim produces a shorter MP4 with correct duration.
//
// METHOCHANNEL OWNERSHIP (Opus M1):
//   This widget owns _channel.setMethodCallHandler.
//   It delegates ALL callbacks to controller.handleNativeCallback().
//   VGEditorController never registers its own handler.
//
// DISPOSAL (Opus M3):
//   Widget dispose() calls disposeAsync() then dispose() on the controller.

