// ──────────────────────────────────────────────────────────────────────────────
// MethodChannel — same shared channel as all Phase 7 dev_ routes.
// This widget OWNS the handler registration; controller delegates from here.
// ──────────────────────────────────────────────────────────────────────────────

const _channel = MethodChannel('vanguard_media_engine');

// ──────────────────────────────────────────────────────────────────────────────
// VanguardEditorControllerPlayground
