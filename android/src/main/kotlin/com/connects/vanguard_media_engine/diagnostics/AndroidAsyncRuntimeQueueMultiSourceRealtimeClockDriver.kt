    fun run(
        runConfig: RunConfig,
        drainEventsFn: (() -> Int)? = null,
        duckRestorePlane: DuckRestoreEventPlane? = null,
        focusLossPauseResumePlane: FocusLossPauseResumeEventPlane? = null,
    ): RunResult {
        config = runConfig
        this.drainEventsFn = drainEventsFn
        this.duckRestorePlane = duckRestorePlane
        this.focusLossPauseResumePlane = focusLossPauseResumePlane
        deadline = SystemClock.elapsedRealtime() + config.deadlineMs
        mfpm = config.maxFramesPerMix.toLong()
        runThreadId = Thread.currentThread().id
        val s = AndroidAsyncRuntimeQueueMultiSourceRealtimeClockNativeSession(deadline) { frames ->
            onOutputFramesRead(frames)
        }
        session = s
        val extractor = MediaExtractor()
        var codec: MediaCodec? = null

        try {
            if (config.sourcePath.isBlank()) throw FailClosed("source_path_required")
            val windowSec = minOf(config.durationSec, HARD_MAX_DURATION_SEC)
            if (windowSec <= 0.0) throw FailClosed("invalid_decode_duration")
            if (config.seekTargetSec <= 0.0 || config.seekTargetSec >= windowSec) {
                throw FailClosed("invalid_seek_target")
            }
            // The frozen budgets must sit safely inside the actual media
            // decoded per phase (priming/trim tolerance).
            if (config.preSeekBudgetSec <= 0.0 ||
                config.preSeekBudgetSec >
                config.seekTargetSec - PRE_SEEK_SUPPLY_MARGIN_SEC
            ) {
                throw FailClosed("invalid_pre_seek_budget")
            }
            if (config.postSeekBudgetSec <= 0.0 ||
                config.postSeekBudgetSec >
                windowSec - config.seekTargetSec - POST_SEEK_SUPPLY_MARGIN_SEC
            ) {
                throw FailClosed("invalid_post_seek_budget")
            }
            val windowUs = (windowSec * 1_000_000.0).toLong()
            val seekTargetUs = (config.seekTargetSec * 1_000_000.0).toLong()

            extractor.setDataSource(config.sourcePath)
            var audioTrackIndex = -1
            var trackFormat: MediaFormat? = null
            for (i in 0 until extractor.trackCount) {
                val format = extractor.getTrackFormat(i)
                if (format.getString(MediaFormat.KEY_MIME)?.startsWith("audio/") == true) {
                    audioTrackIndex = i
                    trackFormat = format
                    break
                }
            }
            if (audioTrackIndex < 0 || trackFormat == null) throw FailClosed("no_audio_track")
            extractor.selectTrack(audioTrackIndex)

            val mime = trackFormat.getString(MediaFormat.KEY_MIME)
                ?: throw FailClosed("audio_track_mime_missing")
            val dec = MediaCodec.createDecoderByType(mime)
            codec = dec
            dec.configure(trackFormat, null, null, 0)
            dec.start()

            var scratch: ByteBuffer? = null

            // Reads the current decoder output format; a missing
            // KEY_PCM_ENCODING means ENCODING_PCM_16BIT.
            fun readOutputFormat(): Triple<Int, Int, Int> {
                val f = dec.outputFormat
                val sr = f.getInteger(MediaFormat.KEY_SAMPLE_RATE)
                val ch = f.getInteger(MediaFormat.KEY_CHANNEL_COUNT)
                val enc = if (f.containsKey(MediaFormat.KEY_PCM_ENCODING)) {
                    f.getInteger(MediaFormat.KEY_PCM_ENCODING)
                } else {
                    AudioFormat.ENCODING_PCM_16BIT
                }
                return Triple(sr, ch, enc)
            }

            // First format resolution: validates PCM16 + 1-2 channels,
            // freezes the window-aligned frame budgets from the REAL sample
            // rate, verifies the native one-second timing window fits the
            // pre-seek epoch, creates the muted AudioTrack sink and the
            // driver-owned direct read buffer, then creates the two-track
            // realtime native session (worker boots here) plus the lockstep
            // pump. The native start is NOT enqueued yet: the pre-start
            // lockstep source fill quota comes first.
            fun establishSession() {
                val (sr, ch, enc) = readOutputFormat()
                if (enc != AudioFormat.ENCODING_PCM_16BIT) {
                    throw FailClosed("unsupported_pcm_encoding:$enc")
                }
                if (ch != 1 && ch != 2) throw FailClosed("unsupported_channel_count:$ch")
                if (sr < 8000 || sr > 192000) throw FailClosed("invalid_sample_rate:$sr")
                sampleRate = sr
                channelCount = ch
                pcmEncoding = enc
                bytesPerFrame = 2 * ch
                preSeekFrames =
                    (config.preSeekBudgetSec * sr).toLong() / mfpm * mfpm
                postSeekFrames =
                    (config.postSeekBudgetSec * sr).toLong() / mfpm * mfpm
                // The native one-second timing gate spans
                // [F0, F0 + sampleRate] frames with F0 the first window
                // boundary >= the warmup floor; the whole window must
                // render inside the pre-seek epoch or the run cannot make
                // its primary realtime claim.
                val timingF0 = ceilDiv(TIMING_WARMUP_FRAMES, mfpm) * mfpm
                if (preSeekFrames < timingF0 + sr.toLong()) {
                    throw FailClosed("timing_window_unavailable")
                }
                if (postSeekFrames < 2L * mfpm) {
                    throw FailClosed("post_seek_budget_too_small")
                }
                expectedFrames = preSeekFrames + postSeekFrames
                createMutedAudioTrack(sr, ch)
                val readBuf = ByteBuffer
                    .allocateDirect(config.outputRingCapacityFrames * bytesPerFrame)
                    .order(ByteOrder.LITTLE_ENDIAN)
                sinkReadBuf = readBuf
                s.create(
                    sr, ch, expectedFrames,
                    config.sourceRingCapacityFrames,
                    config.outputRingCapacityFrames,
                    config.maxFramesPerMix,
                    readBuf,
                    envelopeProofEnabledIn = config.envelopeProofEnabled,
                )
                // X5 only: the reference mix model applies the exact native
                // per-frame envelope gains; null keeps the X4 unit-gain
                // clamp16(s0 + s1) model untouched.
                val envelopeGainModel: ((Int, Long) -> Double)? =
                    if (config.envelopeProofEnabled) {
                        EnvelopeReferenceModel(sr, mfpm, expectedFrames)::gainAt
                    } else {
                        null
                    }
                pump = AndroidAsyncRuntimeQueueMultiSourceRealtimeClockIngestPump(
                    session = s,
                    channelCount = ch,
                    maxFramesPerMix = config.maxFramesPerMix,
                    pollCancellation = { checkDeadline() },
                    drainOutputToSink = { s.drainAvailableOutput() },
                    envelopeGainModel = envelopeGainModel,
                )
                scratch = ByteBuffer.allocateDirect(SCRATCH_FRAMES * bytesPerFrame)
                    .order(ByteOrder.LITTLE_ENDIAN)
                formatProbeOk = true
            }

            // Once the session format is established, a repeated format
            // change with identical sampleRate/channelCount/PCM encoding is
            // benign and counted; any difference is malignant (the
            // AudioTrack format is frozen).
            fun onOutputFormatChanged() {
                if (!s.isCreated) {
                    establishSession()
                    return
                }
                val (sr, ch, enc) = readOutputFormat()
                if (sr == sampleRate && ch == channelCount && enc == pcmEncoding) {
                    decoderBenignFormatChangeCount += 1
                } else {
                    throw FailClosed("malignant_format_change")
                }
            }

            fun minAcceptedBothTracks(): Long =
                minOf(s.totalFramesAcceptedTrack0, s.totalFramesAcceptedTrack1)

            // Completes the post-seek lockstep source prefill: the pending
            // output ack is consumed via the ack-only read, a fresh sink
            // epoch opens (re-preroll then play happen on the next drains),
            // and only then may a latched pending chunk finish (drains are
            // legal again).
            fun completePostSeekPrefill() {
                postSeekFillFrames = minAcceptedBothTracks() - preSeekFrames
                s.consumeSeekAckAndReanchor()
                openSinkEpoch()
                if (epochFramesWritten != 0L || stagedResidualFrames != 0L) {
                    throw FailClosed("seek_sink_epoch_counters_not_reset")
                }
                seekSinkEpochResetOk = true
                postSeekPrefillActive = false
                pump!!.completePendingLockstep()
            }

            // One already-copied direct slice at byte offset 0, fed through
            // the lockstep pump (which generates the matching synthetic
            // track-1 frames). Ingest-before-drain ordering: prefill phases
            // never read output (the pending output ack must survive until
            // the lockstep quota is met — allowDrain=false latches a
            // stalled chunk and returns the remainder); the steady phase
            // lets the pump's make-room machine drain available output to
            // the sink, so no committed frame is ever dropped.
            fun ingestSlice(sliceBuf: ByteBuffer, sliceFrames: Int) {
                val p = pump!!
                when {
                    !nativeStarted -> {
                        val remaining =
                            p.ingestDecodedSlice(sliceBuf, sliceFrames, allowDrain = false)
                        // A no-drain stall implies one 8192-frame ring is
                        // full, so min(accepted0, accepted1) already
                        // exceeds the 4096-frame quota by geometry.
                        if (minAcceptedBothTracks() >= PRE_START_FILL_FRAMES ||
                            remaining > 0
                        ) {
                            preStartFillFrames = minAcceptedBothTracks()
                            if (preStartFillFrames < PRE_START_FILL_FRAMES) {
                                throw FailClosed("prestart_fill_stalled_below_quota")
                            }
                            s.startAndConsumeAck()
                            nativeStarted = true
                            openSinkEpoch()
                            p.completePendingLockstep()
                            if (remaining > 0 &&
                                p.ingestDecodedSlice(sliceBuf, remaining, allowDrain = true) != 0
                            ) {
                                throw FailClosed("post_start_slice_ingest_incomplete")
                            }
                        }
                    }
                    postSeekPrefillActive -> {
                        val remaining =
                            p.ingestDecodedSlice(sliceBuf, sliceFrames, allowDrain = false)
                        val filled = minAcceptedBothTracks() - preSeekFrames
                        // A stall implies the quota is already exceeded
                        // (each source ring's capacity >= the quota).
                        if (filled >= minOf(PRE_START_FILL_FRAMES, postSeekFrames) ||
                            remaining > 0
                        ) {
                            completePostSeekPrefill()
                            if (remaining > 0 &&
                                p.ingestDecodedSlice(sliceBuf, remaining, allowDrain = true) != 0
                            ) {
                                throw FailClosed("post_seek_slice_ingest_incomplete")
                            }
                        }
                    }
                    else -> {
                        if (p.ingestDecodedSlice(sliceBuf, sliceFrames, allowDrain = true) != 0) {
                            throw FailClosed("steady_slice_ingest_incomplete")
                        }
                    }
                }
            }

            // Streams decoder output into the lockstep realtime rig. Phase
            // 1 stops exactly at the pre-seek budget (in-flight codec state
            // is discarded later by the post-seek flush); phase 2 ingests
            // to the total budget and then runs the codec out to output
            // EOS, discarding surplus with honest accounting.
            fun decodePhase(endUs: Long, phase1: Boolean) {
                val info = MediaCodec.BufferInfo()
                var inputDone = false
                while (true) {
                    checkDeadline()
                    val budgetEnd = if (phase1) preSeekFrames else expectedFrames
                    if (phase1 && s.isCreated &&
                        pump!!.framesCommitted >= budgetEnd
                    ) {
                        return
                    }
                    if (!inputDone) {
                        val inIdx = dec.dequeueInputBuffer(DEQUEUE_TIMEOUT_US)
                        if (inIdx >= 0) {
                            val inBuf = dec.getInputBuffer(inIdx)!!
                            val size = extractor.readSampleData(inBuf, 0)
                            if (size < 0 || extractor.sampleTime > endUs) {
                                dec.queueInputBuffer(
                                    inIdx, 0, 0, 0, MediaCodec.BUFFER_FLAG_END_OF_STREAM
                                )
                                inputDone = true
                            } else {
                                dec.queueInputBuffer(inIdx, 0, size, extractor.sampleTime, 0)
                                extractor.advance()
                            }
                        }
                    }
                    val outIdx = dec.dequeueOutputBuffer(info, DEQUEUE_TIMEOUT_US)
                    when {
                        outIdx == MediaCodec.INFO_OUTPUT_FORMAT_CHANGED -> onOutputFormatChanged()
                        outIdx >= 0 -> {
                            val isEos =
                                (info.flags and MediaCodec.BUFFER_FLAG_END_OF_STREAM) != 0
                            if (info.size > 0) {
                                if (!s.isCreated) establishSession()
                                if (info.size % bytesPerFrame != 0) {
                                    dec.releaseOutputBuffer(outIdx, false)
                                    throw FailClosed("codec_chunk_shape_invalid:${info.size}")
                                }
                                val chunkFrames = info.size / bytesPerFrame
                                totalFramesExtracted += chunkFrames
                                // Re-read the phase budget here: the first
                                // chunk's establishSession() call above is
                                // what froze the budgets. framesCommitted
                                // (accepted plus any latched lockstep
                                // chunk) is the truncation axis so the
                                // budget lands exactly.
                                val budget =
                                    if (phase1) preSeekFrames else expectedFrames
                                val room = budget - pump!!.framesCommitted
                                val ingestFrames =
                                    minOf(chunkFrames.toLong(), maxOf(0L, room)).toInt()
                                val excess = chunkFrames - ingestFrames
                                if (excess > 0) {
                                    // Never-ingested decoded frames: honest
                                    // media-discontinuity accounting, kept
                                    // out of every identity claim.
                                    if (phase1) {
                                        framesTruncatedAtSeekBoundary += excess
                                    } else {
                                        framesDiscardedAfterBudget += excess
                                    }
                                }
                                if (ingestFrames > 0) {
                                    val sc = scratch!!
                                    val outBuf = dec.getOutputBuffer(outIdx)!!
                                    // Copy the committed leading frames into
                                    // direct slices (scratch first, bounded
                                    // temporaries only on overflow), all at
                                    // byte offset 0, BEFORE releasing the
                                    // codec output buffer; only then may any
                                    // JNI call run.
                                    val sliceCapBytes = sc.capacity()
                                    val slices = ArrayList<Pair<ByteBuffer, Int>>()
                                    var sliceOffset = info.offset
                                    var remainingBytes = ingestFrames * bytesPerFrame
                                    while (remainingBytes > 0) {
                                        val sliceBytes = minOf(remainingBytes, sliceCapBytes)
                                        val dst = if (slices.isEmpty()) {
                                            sc
                                        } else {
                                            ByteBuffer.allocateDirect(sliceBytes)
                                                .order(ByteOrder.LITTLE_ENDIAN)
                                        }
                                        outBuf.position(sliceOffset)
                                        outBuf.limit(sliceOffset + sliceBytes)
                                        dst.clear()
                                        dst.put(outBuf)
                                        slices.add(dst to sliceBytes / bytesPerFrame)
                                        sliceOffset += sliceBytes
                                        remainingBytes -= sliceBytes
                                    }
                                    dec.releaseOutputBuffer(outIdx, false)
                                    for ((sliceBuf, sliceFrames) in slices) {
                                        ingestSlice(sliceBuf, sliceFrames)
                                    }
                                } else {
                                    dec.releaseOutputBuffer(outIdx, false)
                                }
                            } else {
                                dec.releaseOutputBuffer(outIdx, false)
                            }
                            if (isEos) {
                                if (phase1) {
                                    if (s.isCreated &&
                                        pump!!.framesCommitted >= preSeekFrames
                                    ) {
                                        return
                                    }
                                    throw FailClosed("decoder_eos_before_pre_seek_budget")
                                }
                                if (pump!!.framesCommitted < expectedFrames) {
                                    throw FailClosed("decoder_eos_before_post_seek_budget")
                                }
                                decoderEosReachedOk = true
                                return
                            }
                        }
                        // INFO_TRY_AGAIN_LATER — the deadline bounds the wait.
                    }
                }
            }

            // ── Phase 1: lockstep pre-start fill, native start, realtime
            // pre-seek epoch (the native timing + backlog gates run here) ─────
            decodePhase(seekTargetUs, phase1 = true)
            if (!s.isCreated) throw FailClosed("no_decoder_output")
            if (!nativeStarted) throw FailClosed("prestart_fill_never_completed")
            detailParts.add("preStartFillFrames=$preStartFillFrames")

            // ── The one pre-EOS JOINT native seek at the aligned lockstep
            // budget boundary, with the AudioTrack sink paused + flushed at
            // quiescence and NO caller-supplied time. Both tracks re-anchor
            // at one accepted frame cursor; the synthetic generator is then
            // explicitly re-anchored at that same frame ──────────────────────
            val seekFrame = s.seekAtQuiescentBoundary { onSinkSeekBoundary() }
            if (seekFrame != preSeekFrames) throw FailClosed("seek_frame_budget_mismatch")
            seekTargetFrame = seekFrame
            pump!!.reanchorSyntheticGenerator(seekFrame)
            detailParts.add("seekAcceptedFrame=$seekFrame")
            detailParts.add("generatorReanchorCount=${pump!!.generatorReanchorCount}")
            detailParts.add("framesDiscardedInSinkAtSeek=$framesDiscardedInSinkAtSeek")
            detailParts.add("post_seek_media_content_overlap_permitted")

            // Extractor seek stays media-local; PREVIOUS_SYNC may land early
            // and re-decode content already ingested pre-seek (non-claim
            // recorded above). flush() discards in-flight codec state.
            extractor.seekTo(seekTargetUs, MediaExtractor.SEEK_TO_PREVIOUS_SYNC)
            val postSeekStartUs =
                extractor.sampleTime.let { if (it >= 0L) it else seekTargetUs }
            dec.flush()
            detailParts.add("postSeekStartUs=$postSeekStartUs")

            // ── Phase 2: post-seek lockstep source prefill (worker parked
            // on the pending output ack), ack consume + fresh sink epoch,
            // realtime post-seek epoch, then codec EOS run-out ───────────────
            postSeekPrefillActive = true
            decodePhase(postSeekStartUs + (windowUs - seekTargetUs), phase1 = false)
            if (postSeekPrefillActive) {
                // Defensive: the whole post-seek budget fit under the fill
                // quota, so the ack was never consumed inside the loop.
                completePostSeekPrefill()
            }
            detailParts.add("postSeekFillFrames=$postSeekFillFrames")
            seekEpochReanchorOk = s.seekReanchorOk
            syntheticGeneratorReanchorOk = pump!!.generatorReanchorCount == 1L

            // ── Exact timeline completion, then JOINT writer-local EOS ──────
            s.completeTimelineAndSetEos()

            // ── Sink finalization: zero residual, telemetry-only head
            // progression, epoch-1 underrun telemetry ───────────────────────
            finalizeSinkAtEos()

            // ── Final snapshot + verdict lanes ──────────────────────────────
            s.finalSnapshot()
            detailParts.add("preSeekFrames=$preSeekFrames")
            detailParts.add("postSeekFrames=$postSeekFrames")
            detailParts.add("expectedFrames=$expectedFrames")
            detailParts.add(
                "framesTruncatedAtSeekBoundary=$framesTruncatedAtSeekBoundary"
            )
            detailParts.add("framesDiscardedAfterBudget=$framesDiscardedAfterBudget")
            detailParts.add("nativeRealtimeElapsedMs=${s.snapNativeRealtimeElapsedMs}")
            detailParts.add("maxRenderCursorBacklogUs=${s.snapMaxRenderCursorBacklogUs}")
            detailParts.add("workerNoFramesDueWaits=${s.snapWorkerNoFramesDueWaits}")
            detailParts.add("audioTrackTelemetryOnly")

            realtimeWorkerClockOwnershipOk = s.workerOwnershipAtBootOk &&
                s.nodeOwnedTopologyOk &&
                s.snapWorkerThreadDistinct &&
                s.snapOwnerDispatchCalls == 0L &&
                s.snapWorkerDispatchAnomalies == 0L &&
                s.snapNonMonotonicTimeAnomalies == 0L &&
                s.snapSchedulerErrorCount == 0L &&
                s.snapWorkerOwnsMonotonicClock &&
                s.snapRoutedSourceCount == 2L &&
                !s.snapTerminal
            if (!realtimeWorkerClockOwnershipOk) {
                throw FailClosed("realtime_worker_clock_ownership_violated")
            }

            noCallerSuppliedNativeTimeOk = s.snapNoCallerSuppliedNativeTime
            if (!noCallerSuppliedNativeTimeOk) {
                throw FailClosed("caller_supplied_native_time_detected")
            }

            controlCommandSerializationOk = s.snapCommandsEnqueued == 2L &&
                s.snapCommandsProcessed == 2L &&
                s.snapCommandErrors == 0L &&
                s.snapLastCommandSeq == 2L &&
                s.snapQueueDepth == 0L
            if (!controlCommandSerializationOk) {
                throw FailClosed("command_serialization_mismatch")
            }

            // Primary native realtime gates, computed by the worker on its
            // own steady_clock reads and only folded here.
            realtimeNativeElapsedOk = s.snapRealtimeElapsedOk &&
                s.snapNativeRealtimeElapsedMs in 980L..1350L
            if (!realtimeNativeElapsedOk) {
                throw FailClosed(
                    "realtime_elapsed_gate_failed:${s.snapNativeRealtimeElapsedMs}ms"
                )
            }
            realtimeBacklogBoundOk = s.snapRealtimeBacklogBoundOk &&
                s.snapMaxRenderCursorBacklogUs in 0L until 250_000L &&
                s.snapBacklogSampleCount >= 1L
            if (!realtimeBacklogBoundOk) {
                throw FailClosed(
                    "realtime_backlog_gate_failed:${s.snapMaxRenderCursorBacklogUs}us"
                )
            }

            // Reference-model verdict: per-track input identities, the
            // clamp16(s0+s1) mix identity through the output ring and the
            // sink write path, and the two-track contribution proof.
            val kotlinSinkHex = String.format("%016x", kotlinSinkChecksum)
            val verdict = pump!!.verifyReferenceModel(kotlinSinkHex)
            trackFrameAxisLockstepOk = verdict.trackFrameAxisLockstepOk
            referenceMixChecksumOk = verdict.referenceMixChecksumOk &&
                verdict.nativeReadChecksumMatchesSinkOk
            twoTrackContributionOk = verdict.twoTrackContributionOk

            // Per-track provider poisoning counters must all be zero.
            providerPoisoningOk =
                s.snapProviderFramesZeroFilledTrack[0] == 0L &&
                    s.snapProviderFramesZeroFilledTrack[1] == 0L &&
                    s.snapProviderUnderrunEventsTrack[0] == 0L &&
                    s.snapProviderUnderrunEventsTrack[1] == 0L &&
                    s.snapProviderForwardSkipFramesTrack[0] == 0L &&
                    s.snapProviderForwardSkipFramesTrack[1] == 0L &&
                    s.snapProviderRewindRejectsTrack[0] == 0L &&
                    s.snapProviderRewindRejectsTrack[1] == 0L
            if (!providerPoisoningOk) throw FailClosed("provider_poisoning_observed")

            // Identity chain: both track input identities, the mix identity
            // (kotlinReferenceMix == nativeOutputRead == kotlinSinkWrite),
            // and zero poisoning. silenceCount == 0 is generator/ingest
            // dependent (the joint dispatch gate keeps it zero), asserted
            // here rather than claimed structurally.
            checksumIdentityOk = referenceMixChecksumOk &&
                pump!!.kotlinTrack0AcceptedChecksumHex == s.nativeAcceptedChecksumHexTrack0 &&
                pump!!.kotlinTrack1AcceptedChecksumHex == s.nativeAcceptedChecksumHexTrack1 &&
                providerPoisoningOk &&
                s.snapSilenceCount == 0L
            if (!checksumIdentityOk) throw FailClosed("checksum_identity_mismatch")

            // Frame accounting with the explicit pre/post seek split:
            // accepted/rendered/pushed/read/sink totals all equal the
            // frozen expected timeline on both tracks.
            frameAccountingOk =
                preSeekFrames + postSeekFrames == expectedFrames &&
                    s.totalFramesAcceptedTrack0 == expectedFrames &&
                    s.totalFramesAcceptedTrack1 == expectedFrames &&
                    pump!!.kotlinFramesAccepted == expectedFrames &&
                    s.snapTotalFramesRendered == expectedFrames &&
                    s.snapTotalFramesPushed == expectedFrames &&
                    s.totalOutputFramesRead == expectedFrames
            if (!frameAccountingOk) throw FailClosed("frame_accounting_mismatch")

            // Lossless sink accounting gate: framesWrittenToSink +
            // residualFramesAtEnd(0) == totalOutputFramesRead ==
            // expectedFrames.
            sinkWriteAccountingOk = stagedResidualFrames == 0L &&
                framesWrittenToSinkTotal == framesReadFromRingTotal &&
                framesReadFromRingTotal == s.totalOutputFramesRead &&
                s.totalOutputFramesRead == expectedFrames &&
                framesDiscardedInSinkAtSeek >= 0L
            if (!sinkWriteAccountingOk) throw FailClosed("sink_write_accounting_mismatch")

            multiSourceRealDecoderIngestOk =
                s.totalFramesAcceptedTrack0 == expectedFrames &&
                    totalFramesExtracted >= expectedFrames &&
                    preStartFillFrames >= PRE_START_FILL_FRAMES &&
                    pump!!.track1NonZeroSampleCount > 0L
            if (!multiSourceRealDecoderIngestOk) {
                throw FailClosed("multi_source_real_decoder_ingest_shortfall")
            }

            if (!syntheticGeneratorReanchorOk) {
                throw FailClosed("synthetic_generator_reanchor_missing")
            }

            noOwnerThreadDispatchOk = s.snapOwnerDispatchCalls == 0L &&
                s.snapWorkerThreadDistinct
            if (!noOwnerThreadDispatchOk) throw FailClosed("owner_thread_dispatch_observed")

            canonicalProofBoundaryOk = s.snapProofBoundary ==
                AndroidAsyncRuntimeQueueMultiSourceRealtimeClockNativeSession
                    .NATIVE_PROOF_BOUNDARY
            if (!canonicalProofBoundaryOk) throw FailClosed("native_proof_boundary_mismatch")

            // X5 dynamic-gain-envelope gate. Envelope mode requires the
            // worker-folded telemetry to prove a DYNAMIC envelope actually
            // shaped the mix (applied, evaluated, min strictly below max,
            // both inside [0,1]); the default X4 mode requires the exact
            // no-envelope defaults so unit-gain behavior is proven
            // preserved. The checksum identity above already bound the
            // envelope math bit-exactly in envelope mode.
            dynamicGainEnvelopeOk = if (config.envelopeProofEnabled) {
                s.snapEnvelopeProofEnabled &&
                    s.snapEnvelopeApplied &&
                    s.snapEnvelopeEvaluations > 0L &&
                    s.snapMinEffectiveGain >= 0.0 &&
                    s.snapMaxEffectiveGain <= 1.0 &&
                    s.snapMinEffectiveGain < s.snapMaxEffectiveGain
            } else {
                !s.snapEnvelopeProofEnabled &&
                    !s.snapEnvelopeApplied &&
                    s.snapEnvelopeEvaluations == 0L
            }
            if (!dynamicGainEnvelopeOk) {
                throw FailClosed("dynamic_gain_envelope_gates_failed")
            }
            detailParts.add("envelopeProofEnabled=${config.envelopeProofEnabled}")
            detailParts.add("envelopeEvaluations=${s.snapEnvelopeEvaluations}")

            // X6 non-zero-gain sink proof gate. Only evaluated when
            // nonZeroGainSinkProofEnabled=true; composites the gain-set
            // fact with existing accounting/checksum/frame gates. Volume
            // does not alter written PCM bytes; checksums are preserved.
            // Terminal states encoded here: format_frozen_volume_set ->
            // prerolled_not_playing -> playing -> stopped_at_eos ->
            // released_once (see driver-level terminal-state table).
            // Deferred: no acoustic/speaker measurement, no loudness/SNR,
            // no latency/glitch/xrun/underrun-freedom, no A/V sync, no
            // audio focus/duck/noisy, no route-change, no dead-object
            // recovery, no product/editor/export/streaming/iOS.
            if (config.nonZeroGainSinkProofEnabled) {
                nonZeroGainSinkGatesHeld = nonZeroGainSetOk &&
                    audioTrackGain > 0.0f &&
                    audioTrackGain <= 1.0f &&
                    sinkWriteAccountingOk &&
                    checksumIdentityOk &&
                    frameAccountingOk
                if (!nonZeroGainSinkGatesHeld) {
                    throw FailClosed("nonzero_gain_sink_gates_failed")
                }
                detailParts.add("audioTrackGain=$audioTrackGain")
                detailParts.add("nonZeroGainSinkGatesHeld=true")
            }

            // X8 focus-duck/restore response gate. The synthetic duck must
            // have been drained and applied exactly once (setVolume 0.1
            // SUCCESS), the gain restore exactly once afterwards (setVolume
            // 0.5 SUCCESS), on a strictly later drain pass, ending at the
            // 0.5 base gain. Set-value telemetry only: no measured volume,
            // dB, perceptual depth, fade, ramp, pause/resume, OS focus
            // arbitration correctness, route recovery, or dead-object
            // recovery claim.
            if (config.focusDuckRestoreProofEnabled) {
                if (duckAppliedCount != 1L || !duckSetVolumeOk) {
                    throw FailClosed("duck_not_applied")
                }
                if (restoreAppliedCount != 1L || !restoreSetVolumeOk) {
                    throw FailClosed("restore_not_applied")
                }
                if (duckDrainSeq < 0L || restoreDrainSeq <= duckDrainSeq) {
                    throw FailClosed("duck_restore_order_violated")
                }
                if (x8FinalVolume != 0.5) {
                    throw FailClosed("final_volume_not_restored")
                }
                detailParts.add("duckDrainSeq=$duckDrainSeq")
                detailParts.add("restoreDrainSeq=$restoreDrainSeq")
                detailParts.add("focusDuckRestoreSetVolumeTelemetryOnly")
            }

            // X9 focus-loss pause/resume response gate. Exactly one synthetic
            // transient loss must have been applied (AudioTrack.pause() only,
            // PLAYSTATE_PAUSED asserted), exactly one synthetic focus gain
            // applied at the same owner-thread boundary (AudioTrack.play(),
            // PLAYSTATE_PLAYING asserted), and exactly one synthetic
            // becoming-noisy applied at the terminal EOS point (pause() only,
            // PLAYSTATE_PAUSED asserted, no auto-resume), with a strictly
            // monotonic applied-event sequence. Sink-side playstate proof
            // only: no acoustic audibility/speaker verification, no OS focus
            // arbitration correctness, no transport/presentation pause, no
            // pause/resume SLA, no route-change or dead-object recovery, no
            // production restart policy.
            if (config.focusLossPauseResumeProofEnabled) {
                if (transientLossAppliedCount != 1L || !focusLossPauseOk) {
                    throw FailClosed("focus_loss_pause_not_applied")
                }
                if (focusGainAppliedCount != 1L || !focusGainResumeOk) {
                    throw FailClosed("focus_gain_resume_not_applied")
                }
                if (becomingNoisyAppliedCount != 1L || !becomingNoisyPauseOk) {
                    throw FailClosed("becoming_noisy_pause_not_applied")
                }
                if (transientPauseApplySeq < 0L ||
                    focusGainResumeApplySeq <= transientPauseApplySeq ||
                    noisyPauseApplySeq <= focusGainResumeApplySeq
                ) {
                    throw FailClosed("focus_loss_pause_resume_order_violated")
                }
                if (playStateAfterNoisyPause != AudioTrack.PLAYSTATE_PAUSED) {
                    throw FailClosed("terminal_playstate_not_paused")
                }
                detailParts.add("transientPauseApplySeq=$transientPauseApplySeq")
                detailParts.add("focusGainResumeApplySeq=$focusGainResumeApplySeq")
                detailParts.add("noisyPauseApplySeq=$noisyPauseApplySeq")
                detailParts.add("focusLossPauseResumePlaystateTelemetryOnly")
            }

            // ── Destroy: join-on-destroy + idempotence ──────────────────────
            val (joinOk, idempotentOk) = s.destroyAndVerifyLifecycle()
            workerJoinOnDestroyOk = joinOk
            if (!joinOk) throw FailClosed("worker_join_on_destroy_failed")
            idempotentDestroyOk = idempotentOk
            if (!idempotentOk) throw FailClosed("destroy_not_idempotent")

            // X8: explicit owner-thread release before the result is sealed;
            // releasing with an unrestored duck fails closed, and the release
            // itself disables the volume applier (terminal: stopped_at_eos ->
            // released_once -> applier_disabled). The finally release is then
            // a guarded no-op.
            if (config.focusDuckRestoreProofEnabled) {
                if (duckAppliedCount > restoreAppliedCount) {
                    throw FailClosed("released_while_ducked")
                }
                releaseAudioTrackOnce()
            }

            // X9: explicit owner-thread release before the result is sealed.
            // The transient pause must have been resumed; the terminal
            // becoming-noisy pause is intentionally NOT resumed, so the
            // playstate observed at release must be PLAYSTATE_PAUSED. The
            // release disables the X9 applier (terminal:
            // paused_becoming_noisy -> released_once -> applier_disabled); any
            // later X9 event fails closed. The finally release is then a
            // guarded no-op.
            if (config.focusLossPauseResumeProofEnabled) {
                if (transientLossAppliedCount > focusGainAppliedCount) {
                    throw FailClosed("released_while_focus_paused_unresumed")
                }
                releaseAudioTrackOnce()
                if (playStateAtRelease != AudioTrack.PLAYSTATE_PAUSED) {
                    throw FailClosed(
                        "terminal_playstate_not_paused_before_release:$playStateAtRelease"
                    )
                }
                terminalPlayStatePausedBeforeReleaseOk = true
            }

            // Every sink write and boundary callback asserted the single
            // run thread; native enforced owner-only entry points.
            ownerThreadAffinityOk = true

            return makeResult(pass = true, failureReason = "")
        } catch (f: FailClosed) {
            return makeResult(pass = false, failureReason = f.reason)
        } catch (f: AndroidAsyncRuntimeQueueMultiSourceRealtimeClockNativeSession.Failure) {
            return makeResult(pass = false, failureReason = f.reason)
        } catch (f: AndroidAsyncRuntimeQueueMultiSourceRealtimeClockIngestPump.FailClosed) {
            return makeResult(pass = false, failureReason = f.reason)
        } catch (e: Throwable) {
            return makeResult(
                pass = false,
                failureReason = "exception:${e.javaClass.simpleName}:${e.message}",
            )
        } finally {
            releaseAudioTrackOnce()
            try { codec?.stop() } catch (_: Throwable) {}
            try { codec?.release() } catch (_: Throwable) {}
            try { extractor.release() } catch (_: Throwable) {}
            s.cleanup()
        }
    }

    // ── Session output sink: read accounting + muted AudioTrack write ───────

    // Invoked by the session after every destructive output read with
    // [frames] freshly read mixed PCM16 frames at byte offset 0 of the
    // driver's read buffer. Checksums FIRST (before any write mutates the
    // buffer layout), then stages + writes everything to the muted
    // AudioTrack; the session issues no further native call until this
    // returns with zero staged residual.
    private fun onOutputFramesRead(frames: Long) {
        assertOwnerThread("sink_read")
        val buf = sinkReadBuf ?: throw FailClosed("sink_read_before_create")
        val sampleCount = (frames * channelCount).toInt()
        var c = kotlinSinkChecksum
        for (i in 0 until sampleCount) {
            c = c * 31L + (buf.getShort(i * 2).toLong() and 0xFFFFL)
        }
        kotlinSinkChecksum = c
        framesReadFromRingTotal += frames
        stagedResidualFrames = frames
        writeAllToAudioTrack((frames * bytesPerFrame).toInt())
        if (stagedResidualFrames != 0L) throw FailClosed("sink_residual_after_write")
    }

    // Writes [bytes] bytes from offset 0 of the read buffer with
    // WRITE_NON_BLOCKING only, fail-closed on every negative status code
    // (including ERROR_DEAD_OBJECT — no recovery claim). Partial writes
    // compact/retain the unwritten remainder in the same buffer and retry;
    // zero writes park briefly under a bounded budget. The per-epoch
    // pre-roll gate opens play() from inside this loop once the quota is
    // written.
    private fun writeAllToAudioTrack(bytes: Int) {
        val track = audioTrack ?: throw FailClosed("audio_track_missing")
        val buf = sinkReadBuf!!
        buf.position(0)
        buf.limit(bytes)
        var consecutiveZero = 0
        while (buf.hasRemaining()) {
            checkDeadline()
            val requested = buf.remaining()
            val wrote = track.write(buf, requested, AudioTrack.WRITE_NON_BLOCKING)
            when {
                wrote > 0 -> {
                    consecutiveZero = 0
                    if (wrote % bytesPerFrame != 0) {
                        throw FailClosed("audio_track_write_frame_misaligned:$wrote")
                    }
                    val framesWritten = (wrote / bytesPerFrame).toLong()
                    epochFramesWritten += framesWritten
                    framesWrittenToSinkTotal += framesWritten
                    stagedResidualFrames -= framesWritten
                    if (wrote < requested) {
                        partialWriteCount++
                        buf.compact()
                        buf.flip()
                    }
                    playIfPrerolled()
                }
                wrote == 0 -> {
                    zeroWriteCount++
                    playIfPrerolled()
                    if (++consecutiveZero > MAX_CONSECUTIVE_ZERO_WRITES) {
                        throw FailClosed("audio_track_write_stalled")
                    }
                    Thread.sleep(ZERO_WRITE_SLEEP_MS)
                }
                wrote == AudioTrack.ERROR_INVALID_OPERATION ->
                    throw FailClosed("audio_track_invalid_operation")
                wrote == AudioTrack.ERROR_BAD_VALUE ->
                    throw FailClosed("audio_track_bad_value")
                wrote == AudioTrack.ERROR_DEAD_OBJECT ->
                    throw FailClosed("audio_track_dead_object")
                else -> throw FailClosed("audio_track_write_error:$wrote")
            }
        }
        buf.clear()
        // X7 drain point: owner thread, after write loop completes.
        drainEventsFn?.invoke()
        // X8 drain point: at most one synthetic duck/restore event per pass.
        drainOneDuckRestoreEvent()
        // X9 non-terminal drain point: the transient loss pause + same-boundary
        // focus-gain resume are applied here (never at the seek boundary).
        drainFocusLossPauseResumeNonTerminal()
    }

    // ── AudioTrack lifecycle / pre-roll / seek epoch ────────────────────────

    private fun createMutedAudioTrack(sampleRate: Int, channelCount: Int) {
        val channelMask = if (channelCount == 1) {
            AudioFormat.CHANNEL_OUT_MONO
        } else {
            AudioFormat.CHANNEL_OUT_STEREO
        }
        val minBytes = AudioTrack.getMinBufferSize(
            sampleRate, channelMask, AudioFormat.ENCODING_PCM_16BIT
        )
        if (minBytes <= 0) throw FailClosed("audio_track_min_buffer_invalid:$minBytes")
        // The buffer floor keeps one full output-ring drain writable before
        // play() so the pre-roll write span can never stall.
        val floorBytes = ((config.outputRingCapacityFrames.toLong() +
            TRACK_BUFFER_MARGIN_WINDOWS * mfpm) * bytesPerFrame).toInt()
        // Rounded up to a whole mix window so a start-threshold-raised
        // pre-roll quota (a window multiple) always fits the buffer.
        val windowBytes = (mfpm * bytesPerFrame).toInt()
        val requestedBytes =
            ((maxOf(minBytes, floorBytes) + windowBytes - 1) / windowBytes) * windowBytes
        val track = AudioTrack.Builder()
            .setAudioAttributes(
                AudioAttributes.Builder()
                    .setUsage(AudioAttributes.USAGE_MEDIA)
                    .setContentType(AudioAttributes.CONTENT_TYPE_MUSIC)
                    .build()
            )
            .setAudioFormat(
                AudioFormat.Builder()
                    .setEncoding(AudioFormat.ENCODING_PCM_16BIT)
                    .setSampleRate(sampleRate)
                    .setChannelMask(channelMask)
                    .build()
            )
            .setTransferMode(AudioTrack.MODE_STREAM)
            .setBufferSizeInBytes(requestedBytes)
            .build()
        audioTrack = track
        if (track.state != AudioTrack.STATE_INITIALIZED) {
            throw FailClosed("audio_track_not_initialized")
        }
        if (config.nonZeroGainSinkProofEnabled ||
            config.focusDuckRestoreProofEnabled ||
            config.focusLossPauseResumeProofEnabled
        ) {
            // X6 non-zero-gain proof (and X8/X9, which imply the non-zero
            // base gain): constant AudioTrack output gain only. Written PCM
            // bytes and every checksum are unaffected by this.
            // Terminal state: created_uninit -> format_frozen_volume_set.
            // Deferred: no acoustic/audibility claim, no route-change
            // handling, no dead-object recovery.
            if (track.setVolume(NONZERO_GAIN_PROOF) != AudioTrack.SUCCESS) {
                throw FailClosed("nonzero_gain_volume_set_failed")
            }
            nonZeroGainSetOk = true
            audioTrackGain = NONZERO_GAIN_PROOF
            if (config.focusDuckRestoreProofEnabled) {
                // X8 terminal state: created_uninit -> base_volume_set(0.5);
                // the duck/restore volume applier is live from here until
                // release disables it.
                x8BaseVolumeSet = true
                x8BaseVolume = 0.5
                x8FinalVolume = 0.5
                x8ApplierEnabled = true
            }
            if (config.focusLossPauseResumeProofEnabled) {
                // X9 terminal state: created_uninit -> base_volume_set(0.5);
                // the pause/resume playstate applier is live from here until
                // release disables it. X8 duck/restore state is NOT touched.
                x9ApplierEnabled = true
            }
        } else {
            // Muted-only boundary: default X4/X5 path (volume 0.0).
            if (track.setVolume(0.0f) != AudioTrack.SUCCESS) {
                throw FailClosed("muted_volume_set_failed")
            }
            mutedOutputOk = true
            audioTrackGain = 0.0f
        }
        bufferSizeInFrames = track.bufferSizeInFrames.toLong()
        prerollFrames = PREROLL_WINDOWS * mfpm
        alignPrerollWithStartThreshold(track)
        audioTrackInitOk = true
    }

    // A MODE_STREAM AudioTrack does not start consuming until its buffer
    // holds the start threshold of frames, which defaults to the full
    // buffer capacity. On API 31+ the threshold is lowered to the pre-roll
    // quota; where that API is unavailable or the device refuses, the
    // per-run pre-roll quota is raised to the effective threshold instead,
    // fail-closed if it cannot fit the track buffer. No latency claim: this
    // only makes the muted diagnostic sink start at all under non-blocking
    // writes.
    private fun alignPrerollWithStartThreshold(track: AudioTrack) {
        var effectiveThreshold = bufferSizeInFrames
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            effectiveThreshold = try {
                track.setStartThresholdInFrames(
                    prerollFrames.coerceAtMost(bufferSizeInFrames).toInt()
                ).toLong()
            } catch (_: Throwable) {
                bufferSizeInFrames
            }
        }
        startThresholdFrames = effectiveThreshold
        val neededPreroll = maxOf(prerollFrames, effectiveThreshold)
        prerollFrames = ceilDiv(neededPreroll, mfpm) * mfpm
        if (prerollFrames > bufferSizeInFrames) {
            throw FailClosed(
                "preroll_exceeds_track_buffer:$prerollFrames:$bufferSizeInFrames"
            )
        }
    }

    // Per-epoch pre-roll gate: play() only after the aligned quota is
    // written this epoch; asserts PLAYSTATE_PLAYING and captures the
    // underrun telemetry baseline.
    private fun playIfPrerolled() {
        if (epochPlayed || epochFramesWritten < prerollFrames) return
        val track = audioTrack ?: throw FailClosed("audio_track_missing")
        track.play()
        if (track.playState != AudioTrack.PLAYSTATE_PLAYING) {
            throw FailClosed("audio_track_not_playing_after_play")
        }
        epochPlayed = true
        epochUnderrunBaseline = readUnderrunTelemetry()
        if (underrunBaselineFirst < 0L) underrunBaselineFirst = epochUnderrunBaseline
    }

    // Runs at the seek quiescent boundary (inside the session's seek, after
    // the full boundary drain, before the native joint seek is enqueued):
    // zero staged residual asserted, epoch-0 sink discard accounting
    // captured and excluded from identity, then AudioTrack pause() +
    // flush().
    private fun onSinkSeekBoundary() {
        assertOwnerThread("seek_boundary")
        if (stagedResidualFrames != 0L) throw FailClosed("seek_with_staged_residual")
        if (!epochPlayed) throw FailClosed("seek_before_epoch_play")
        val track = audioTrack ?: throw FailClosed("audio_track_missing")
        sampleTimestampTelemetry()
        framesWrittenBeforeSeek = epochFramesWritten
        playbackHeadAtSeek = epochHeadProgress()
        framesDiscardedInSinkAtSeek = framesWrittenBeforeSeek - playbackHeadAtSeek
        if (framesDiscardedInSinkAtSeek < 0L) {
            throw FailClosed("seek_sink_discard_accounting_negative")
        }
        captureEpochUnderrunDelta("epoch0")
        // X9 invariant: a transient focus-loss pause must have been resumed
        // at its own owner-thread boundary before the seek epoch pause/flush
        // may run. X9 events are never drained here (the seek pause/flush
        // resets the epoch; applying pause/play inside it would be unsafe).
        if (config.focusLossPauseResumeProofEnabled &&
            transientLossAppliedCount > focusGainAppliedCount
        ) {
            throw FailClosed("seek_boundary_while_focus_paused_unresumed")
        }
        track.pause()
        if (track.playState != AudioTrack.PLAYSTATE_PAUSED) {
            throw FailClosed("audio_track_not_paused_at_seek")
        }
        track.flush()
        // X7 drain point: owner thread, at seek boundary.
        drainEventsFn?.invoke()
        // X8 drain point: at most one synthetic duck/restore event per pass.
        drainOneDuckRestoreEvent()
    }

    // Post-EOS sink finalization: zero staged residual, epoch-1 head
    // progression under a bounded wait (TELEMETRY lane only; the head never
    // becomes a native anchor, timebase, or correction), epoch-1 underrun
    // telemetry.
    private fun finalizeSinkAtEos() {
        assertOwnerThread("sink_finalize")
        if (stagedResidualFrames != 0L) throw FailClosed("sink_residual_at_end")
        if (!epochPlayed) throw FailClosed("post_seek_epoch_never_played")
        sampleTimestampTelemetry()
        val waitDeadline = minOf(
            deadline, SystemClock.elapsedRealtime() + HEAD_PROGRESS_WAIT_MS
        )
        var progress = epochHeadProgress()
        while (progress <= 0L && SystemClock.elapsedRealtime() <= waitDeadline) {
            Thread.sleep(HEAD_POLL_SLEEP_MS)
            progress = epochHeadProgress()
        }
        playbackHeadFinal = progress
        playbackHeadTelemetryOk = progress > 0L && playbackHeadAtSeek >= 0L
        if (!playbackHeadTelemetryOk) throw FailClosed("playback_head_not_progressed")
        captureEpochUnderrunDelta("epoch1")
        // X7 drain point: owner thread, at EOS finalization.
        drainEventsFn?.invoke()
        // X8 drain point: at most one synthetic duck/restore event per pass.
        drainOneDuckRestoreEvent()
        // X9 terminal drain point: the ONE synthetic becoming-noisy event is
        // applied here (AudioTrack.pause() only, no flush/stop, no resume
        // before release).
        drainFocusLossPauseResumeTerminal()
    }

    // ── X8 focus-duck/restore volume applier (owner thread only) ────────────

    // Polls AT MOST ONE synthetic duck/restore event per drain pass, only
    // once the current epoch has entered playing_base. Every pass advances
    // the drain sequence so duckDrainSeq < restoreDrainSeq proves ordering.
    private fun drainOneDuckRestoreEvent() {
        val plane = duckRestorePlane ?: return
        if (!config.focusDuckRestoreProofEnabled) return
        assertOwnerThread("x8_drain")
        if (!epochPlayed) return
        val seq = x8DrainSeq++
        val event = plane.pollOneEvent() ?: return
        applyDuckRestoreEvent(event, seq)
    }

    // Applies one typed synthetic event via AudioTrack.setVolume on the owner
    // thread. Set-value telemetry only: no measured volume, dB, perceptual
    // depth, fade, ramp, pause/resume, OS arbitration correctness, route
    // recovery, or dead-object recovery claim. Fail-closed state machine:
    // duck requires the 0.5 base, restore requires the applied duck, each is
    // applied exactly once, and nothing may run after release disables the
    // applier.
    private fun applyDuckRestoreEvent(event: String, seq: Long) {
        val track = audioTrack
        if (!x8ApplierEnabled || track == null) {
            throw FailClosed(
                if (event == X8_EVENT_DUCK) "duck_after_release"
                else "restore_after_release"
            )
        }
        when (event) {
            X8_EVENT_DUCK -> {
                if (!x8BaseVolumeSet) throw FailClosed("duck_without_base")
                if (duckAppliedCount > 0L) throw FailClosed("duplicate_duck")
                if (track.setVolume(DUCK_GAIN_PROOF) != AudioTrack.SUCCESS) {
                    throw FailClosed("duck_set_volume_failed")
                }
                duckSetVolumeOk = true
                duckAppliedCount = 1L
                duckDrainSeq = seq
                x8DuckedVolume = 0.1
                x8FinalVolume = 0.1
                // Report duck drained/applied so the coordinator may post the
                // synthetic gain restore strictly afterwards.
                duckRestorePlane?.onDuckApplied()
            }
            X8_EVENT_GAIN -> {
                if (duckAppliedCount == 0L) throw FailClosed("restore_without_duck")
                if (restoreAppliedCount > 0L) throw FailClosed("duplicate_restore")
                if (track.setVolume(NONZERO_GAIN_PROOF) != AudioTrack.SUCCESS) {
                    throw FailClosed("restore_set_volume_failed")
                }
                restoreSetVolumeOk = true
                restoreAppliedCount = 1L
                restoreDrainSeq = seq
                x8RestoredVolume = 0.5
                x8FinalVolume = 0.5
            }
            else -> throw FailClosed("unknown_duck_restore_event:$event")
        }
    }

    // ── X9 focus-loss pause/resume playstate applier (owner thread only) ────

    // Non-terminal drain point (write loop only): polls AT MOST ONE typed
    // event once the current epoch is playing, and only until the transient
    // pause/resume cycle has completed. After that the queue is deliberately
    // left untouched so the becoming-noisy event can only be applied at the
    // terminal EOS point; a becoming-noisy polled here fails closed.
    private fun drainFocusLossPauseResumeNonTerminal() {
        val plane = focusLossPauseResumePlane ?: return
        if (!config.focusLossPauseResumeProofEnabled) return
        assertOwnerThread("x9_drain")
        if (!epochPlayed) return
        if (focusGainAppliedCount > 0L) return
        val event = plane.pollOneEvent() ?: return
        applyFocusLossPauseResumeEvent(event, terminal = false)
    }

    // Terminal drain point (EOS finalization only): exactly ONE
    // becoming-noisy event must be present and nothing may follow it.
    private fun drainFocusLossPauseResumeTerminal() {
        val plane = focusLossPauseResumePlane ?: return
        if (!config.focusLossPauseResumeProofEnabled) return
        assertOwnerThread("x9_terminal_drain")
        if (!epochPlayed) throw FailClosed("becoming_noisy_before_epoch_play")
        val event = plane.pollOneEvent()
            ?: throw FailClosed("becoming_noisy_event_missing")
        if (event != X9_EVENT_BECOMING_NOISY) {
            throw FailClosed("unexpected_terminal_focus_event:$event")
        }
        applyFocusLossPauseResumeEvent(event, terminal = true)
        if (plane.pollOneEvent() != null) {
            throw FailClosed("focus_event_after_becoming_noisy")
        }
    }

    // Applies one typed synthetic X9 event to the AudioTrack playstate on the
    // owner thread. pause()/play() only — never flush()/stop(); playstate
    // assertions are sink-side telemetry, not an acoustic, transport,
    // presentation, OS-arbitration, SLA, or recovery claim. Fail-closed state
    // machine: transient loss requires PLAYING and is applied once; the focus
    // gain is enqueued synchronously by the plane callback and applied at the
    // SAME boundary (requires the applied pause, applied once, resumes to
    // PLAYING); becoming-noisy is terminal-only, requires the applied resume,
    // is applied once, and is never auto-resumed. Nothing may run after
    // release disables the applier. The applied-event sequence is monotonic
    // per applied event (not per drain pass).
    private fun applyFocusLossPauseResumeEvent(event: String, terminal: Boolean) {
        val track = audioTrack
        if (!x9ApplierEnabled || track == null) {
            throw FailClosed("focus_event_after_release:$event")
        }
        when (event) {
            X9_EVENT_TRANSIENT_LOSS -> {
                if (terminal) throw FailClosed("transient_loss_at_terminal_point")
                if (transientLossAppliedCount > 0L) throw FailClosed("duplicate_transient_loss")
                if (track.playState != AudioTrack.PLAYSTATE_PLAYING) {
                    throw FailClosed(
                        "transient_loss_from_non_playing_state:${track.playState}"
                    )
                }
                track.pause()
                playStateAfterTransientPause = track.playState
                if (playStateAfterTransientPause != AudioTrack.PLAYSTATE_PAUSED) {
                    throw FailClosed(
                        "transient_loss_pause_playstate_bad:$playStateAfterTransientPause"
                    )
                }
                focusLossPauseOk = true
                transientLossAppliedCount = 1L
                transientPauseApplySeq = x9AppliedEventSeq++
                // Same-boundary resume: the plane callback enqueues the ONE
                // synthetic focus gain directly (no main-handler wait), and it
                // is polled and applied right here so the paused sink never
                // accumulates a write backlog.
                val plane = focusLossPauseResumePlane
                    ?: throw FailClosed("focus_loss_plane_missing")
                plane.enqueueSyntheticFocusGain()
                val next = plane.pollOneEvent()
                    ?: throw FailClosed("focus_gain_not_enqueued_synchronously")
                if (next != X9_EVENT_FOCUS_GAIN) {
                    throw FailClosed("unexpected_focus_event_after_transient_loss:$next")
                }
                applyFocusLossPauseResumeEvent(next, terminal = false)
            }
            X9_EVENT_FOCUS_GAIN -> {
                if (terminal) throw FailClosed("focus_gain_at_terminal_point")
                if (transientLossAppliedCount == 0L) {
                    throw FailClosed("focus_gain_without_transient_loss")
                }
                if (focusGainAppliedCount > 0L) throw FailClosed("duplicate_focus_gain")
                if (track.playState != AudioTrack.PLAYSTATE_PAUSED) {
                    throw FailClosed("focus_gain_from_non_paused_state:${track.playState}")
                }
                track.play()
                playStateAfterFocusGainResume = track.playState
                if (playStateAfterFocusGainResume != AudioTrack.PLAYSTATE_PLAYING) {
                    throw FailClosed(
                        "focus_gain_resume_playstate_bad:$playStateAfterFocusGainResume"
                    )
                }
                focusGainResumeOk = true
                focusGainAppliedCount = 1L
                focusGainResumeApplySeq = x9AppliedEventSeq++
                // Report the transient resume applied so the coordinator may
                // enqueue the ONE synthetic becoming-noisy strictly afterwards.
                focusLossPauseResumePlane?.onTransientResumeApplied()
            }
            X9_EVENT_BECOMING_NOISY -> {
                if (!terminal) throw FailClosed("becoming_noisy_at_non_terminal_point")
                if (focusGainAppliedCount == 0L) throw FailClosed("becoming_noisy_before_resume")
                if (becomingNoisyAppliedCount > 0L) throw FailClosed("duplicate_becoming_noisy")
                if (track.playState != AudioTrack.PLAYSTATE_PLAYING) {
                    throw FailClosed(
                        "becoming_noisy_from_non_playing_state:${track.playState}"
                    )
                }
                track.pause()
                playStateAfterNoisyPause = track.playState
                if (playStateAfterNoisyPause != AudioTrack.PLAYSTATE_PAUSED) {
                    throw FailClosed(
                        "becoming_noisy_pause_playstate_bad:$playStateAfterNoisyPause"
                    )
                }
                becomingNoisyPauseOk = true
                becomingNoisyAppliedCount = 1L
                noisyPauseApplySeq = x9AppliedEventSeq++
            }
            else -> throw FailClosed("unknown_focus_loss_pause_resume_event:$event")
        }
    }

    // Opens a sink write epoch: zeroed counters, fresh unsigned-masked head
    // baseline (re-read after any flush), cleared play/underrun baselines.
    private fun openSinkEpoch() {
        epochFramesWritten = 0L
        epochPlayed = false
        epochUnderrunBaseline = -1L
        epochHeadBaseline = readPlaybackHeadUnsigned()
    }

    private fun readPlaybackHeadUnsigned(): Long =
        (audioTrack ?: throw FailClosed("audio_track_missing"))
            .playbackHeadPosition.toLong() and 0xFFFF_FFFFL

    private fun epochHeadProgress(): Long {
        val progress = readPlaybackHeadUnsigned() - epochHeadBaseline
        if (progress < 0L) throw FailClosed("playback_head_regressed")
        return progress
    }

    // Device underrun TELEMETRY only: recorded per epoch, reported as-is,
    // never a verdict gate (HAL underrun freedom on this muted diagnostic
    // sink is a non-claim).
    private fun readUnderrunTelemetry(): Long = try {
        audioTrack?.underrunCount?.toLong() ?: -1L
    } catch (_: Throwable) {
        -1L
    }

    private fun captureEpochUnderrunDelta(label: String) {
        val finalCount = readUnderrunTelemetry()
        underrunFinalLast = finalCount
        val delta = if (finalCount >= 0L && epochUnderrunBaseline >= 0L) {
            finalCount - epochUnderrunBaseline
        } else {
            -1L
        }
        if (delta >= 0L) underrunDeltaTotal += delta
        detailParts.add("${label}UnderrunDelta=$delta")
    }

    // AudioTimestamp TELEMETRY only: attempt/success counters, never a
    // verdict gate.
    private fun sampleTimestampTelemetry() {
        val track = audioTrack ?: return
        audioTimestampAttemptCount++
        try {
            if (track.getTimestamp(audioTimestamp)) audioTimestampSuccessCount++
        } catch (_: Throwable) {}
    }

    private fun releaseAudioTrackOnce() {
        val track = audioTrack ?: return
        if (audioTrackReleaseCount > 0) return
        // X8: the duck/restore volume applier is disabled at release; any
        // later duck/restore event fails closed (duck_after_release /
        // restore_after_release).
        x8ApplierEnabled = false
        // X9: capture the sink playstate observed at release (telemetry; the
        // run path gates it to PLAYSTATE_PAUSED) and disable the pause/resume
        // applier; any later X9 event fails closed (focus_event_after_release).
        if (config.focusLossPauseResumeProofEnabled) {
            playStateAtRelease = try { track.playState } catch (_: Throwable) { -1 }
        }
        x9ApplierEnabled = false
        try { track.pause() } catch (_: Throwable) {}
        try { track.flush() } catch (_: Throwable) {}
        try { track.release() } catch (_: Throwable) {}
        audioTrackReleaseCount++
    }

