// ── AndroidAsyncRuntimeQueueMultiSourceRealtimeClockDriver (P4 True-DAG
// sub-slice X4, P4-AUDIO-ASYNC-RUNTIME-QUEUE-MULTI-SOURCE-REALTIME-CLOCK) ───
//
// Kotlin-owned real MediaExtractor/MediaCodec SYNCHRONOUS streaming decode
// (track 0) plus a Kotlin-synthetic PCM track (track 1, generated by
// [AndroidAsyncRuntimeQueueMultiSourceRealtimeClockIngestPump] on the
// shared accepted-frame axis) feeding the TWO node-owned source rings of
// the multi-source realtime-clock async runtime queue native session, with
// the mixed output ring drained into a MUTED android.media.AudioTrack
// MODE_STREAM sink through
// [AndroidAsyncRuntimeQueueMultiSourceRealtimeClockNativeSession]. The
// NATIVE WORKER thread inside the session owns the monotonic
// std::chrono::steady_clock render/dispatch timebase: it reads the clock
// itself for every AudioClock / ClockedAudioTransportCoordinator call and
// paces the GraphAudioScheduler/AudioMixBusNode joint dispatch in
// realtime. Kotlin owns the MediaExtractor/MediaCodec lifecycle, both
// source-ring producer roles, the output-ring consumer role, the
// AudioTrack lifecycle and every write, playback-head/timestamp TELEMETRY,
// deadlines, and cleanup — and never passes a time value into a native
// control command and never dispatches (no step path exists).
//
// X4 proof shape on top of the committed X3 driver
// (AndroidAsyncRuntimeQueueRealtimeClockDriver, untouched):
//   - Lockstep two-track ingest: every decoded chunk is paired with an
//     identical frame count of synthetic PCM before crossing into native;
//     the pre-start (and post-seek) source fill quota applies to
//     min(acceptedFramesTrack0, acceptedFramesTrack1).
//   - The reference mix model is clamp16(s0 + s1) with the shared 31x
//     checksum, so the identity chain is: per-track kotlin accepted ==
//     native accepted, and kotlinReferenceMix == nativeOutputRead ==
//     kotlinSinkWrite.
//   - The one forward seek re-anchors BOTH tracks at a single accepted
//     frame cursor, with an EXPLICIT synthetic generator re-anchor at that
//     frame.
//   - coordinator silenceCount == 0 is asserted as part of the identity;
//     it is generator/ingest-dependent (the joint dispatch gate keeps it
//     zero), not a structural claim.
//   - Fail closed on wrong-owner, queue_full/non-enqueued commands,
//     non-quiescent seek, per-track frame-axis divergence, every negative
//     AudioTrack write status including ERROR_DEAD_OBJECT (no recovery),
//     state/playState mismatch, nonmonotonic native time, deadline
//     exceeded, timing gate fail, backlog bound fail, and residual sink
//     frames at end.
//
// Honest non-claims: see [PROOF_BOUNDARY]. Diagnostic foundation only — no
// audible playback, no presentation-clock claim, no second OS decoder, no
// product/editor/app wiring, no export route, no streaming/cache, no iOS,
// zero C++ primitive changes.
